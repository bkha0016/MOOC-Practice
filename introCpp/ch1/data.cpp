#include <iostream>

int main()
{
	std::cout << 5 << std::endl; // print the literal number 5
	std::cout << -6.7 << std::endl; // print the literal number -6.7
	std::cout << 'H' << std::endl; // print the literal character 'H'
	std::cout << "Hello" << std::endl; // print the literal text 'Hello'
	return 0;
}

